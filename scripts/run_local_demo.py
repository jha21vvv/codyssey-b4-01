#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
==============================================================================
Script Name : run_local_demo.py
Description : 내 윈도우 컴퓨터에서 전체 시스템(앱 실행 -> 관제 -> 로그 적재)을
              클릭 한 번으로 체험할 수 있도록 도와주는 로컬 데모 러너
==============================================================================
"""

# [1차]: 파이썬 내부에서 다른 외부 프로그램(python, bash)을 실행시키는 표준 라이브러리 모듈
# [2차]: 파이썬이 비서처럼 다른 프로그램들을 대신 켜고 끄게 해주는 만능 리모컨
import subprocess

# [1차]: 프로그램 실행 흐름을 지정한 초(second)만큼 잠시 멈추는(sleep) 시간 라이브러리
# [2차]: 점원이 카운터에 앉아서 문을 열 때까지 2초 기다려주는 모래시계
import time

# [1차]: 파일/디렉토리 경로 조작 및 운영체제 환경 변수를 제어하는 OS 표준 모듈
# [2차]: 현재 내 컴퓨터 폴더 주소를 찾고 환경 설정을 주입해주는 내비게이션
import os

# [1차]: 현재 스크립트(run_local_demo.py)가 위치한 상위 폴더(..)의 절대 경로를 계산합니다.
# [2차]: 이 스크립트가 어디서 실행되든 무조건 프로젝트 본사 정문(codyssey-b4-01) 주소를 알아냅니다.
project_root = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))

# [1차]: 현재 작업 디렉토리(Current Working Directory)를 프로젝트 루트 폴더로 변경합니다.
# [2차]: 모든 작업을 프로젝트 본사 1층 로비에 서서 진행하도록 발걸음을 옮깁니다.
os.chdir(project_root)

# ------------------------------------------------------------------------------
# 1. 로컬 실습에 필요한 임시 폴더와 비밀키 파일 준비
# ------------------------------------------------------------------------------

# [1차]: 업로드 파일 저장용 upload_files 디렉토리를 생성합니다. (이미 존재하면 무시: exist_ok=True)
# [2차]: 점원이 일할 때 쓸 공용 택배 창고 방을 만듭니다. (이미 방이 있으면 부수지 않고 그대로 둡니다.)
os.makedirs("upload_files", exist_ok=True)

# [1차]: 암호 인증키를 보관할 api_keys 디렉토리를 생성합니다. (exist_ok=True)
# [2차]: 귀중품을 보관할 비밀 금고 방을 만듭니다.
os.makedirs("api_keys", exist_ok=True)

# [1차]: 관제 일지(로그)를 저장할 logs 디렉토리를 생성합니다. (exist_ok=True)
# [2차]: 매일 순찰 일기장을 보관할 서류 보관실 방을 만듭니다.
os.makedirs("logs", exist_ok=True)

# [1차]: 부팅 2단계 검증(인증키 파일 존재 여부)을 통과하기 위해 api_keys/t_secret.key에 정품 암호 문자열을 기록합니다.
# [2차]: 금고 안에 진짜 열쇠('agent_api_key_test')를 미리 넣어두어 점원이 출근할 때 확인할 수 있게 합니다.
with open("api_keys/t_secret.key", "w", encoding="utf-8") as f:
    f.write("agent_api_key_test\n")

# [1차]: 현재 시스템의 기본 환경 변수 딕셔너리를 안전하게 복사하여 독립된 env 객체를 만듭니다.
# [2차]: 기존 컴퓨터 설정 복사본을 한 장 떠서, 우리 앱에 전달할 맞춤형 근무 지침서를 만듭니다.
env = os.environ.copy()

# [1차]: AGENT_HOME 환경 변수에 프로젝트 루트 디렉토리 절대 경로를 주입합니다.
# [2차]: 근무 지침서에 "너의 일터 본사 주소는 여기야"라고 적어줍니다.
env["AGENT_HOME"] = project_root

# [1차]: AGENT_PORT 환경 변수에 서비스 포트 번호 '15034'를 주입합니다.
# [2차]: 근무 지침서에 "15034번 출입문으로 손님을 받아라"라고 적어줍니다.
env["AGENT_PORT"] = "15034"

# [1차]: AGENT_UPLOAD_DIR 환경 변수에 upload_files 폴더의 절대 경로를 주입합니다.
# [2차]: 근무 지침서에 "손님 택배 상자는 upload_files 방에 쌓아라"라고 적어줍니다.
env["AGENT_UPLOAD_DIR"] = os.path.join(project_root, "upload_files")

# [1차]: AGENT_KEY_PATH 환경 변수에 비밀키 파일의 절대 경로를 주입합니다.
# [2차]: 근무 지침서에 "금고 열쇠는 api_keys/t_secret.key 방에 있다"라고 적어줍니다.
env["AGENT_KEY_PATH"] = os.path.join(project_root, "api_keys", "t_secret.key")

# [1차]: AGENT_LOG_DIR 환경 변수에 logs 디렉토리의 절대 경로를 주입합니다.
# [2차]: 근무 지침서에 "순찰 일지는 logs 방에 적어라"라고 적어줍니다.
env["AGENT_LOG_DIR"] = os.path.join(project_root, "logs")

# ------------------------------------------------------------------------------
# 2. agent_app.py (가게 점원) 백그라운드 출근시키기
# ------------------------------------------------------------------------------

# [1차]: 콘솔에 점원 앱을 백그라운드로 띄운다는 안내 메시지를 출력합니다.
# [2차]: 사용자에게 "가게 점원(agent_app.py) 출근시킵니다!"라고 알려줍니다.
print("[*] Launching agent_app.py in background...")

# [1차]: subprocess.Popen으로 비동기(백그라운드) 서브프로세스를 생성하여 점원 앱(agent_app.py)을 기동합니다.
# [2차]: 점원(agent_app.py)에게 가게 문 열라고 지시해 두고, 파이썬은 점원이 끝날 때까지 멍하니 기다리지 않고 다음 줄로 넘어갑니다.
app_proc = subprocess.Popen(["python", "app/agent_app.py"], env=env)

# [1차]: 앱의 부팅 5단계(포트 바인딩 등)가 완전히 완료되어 대기 상태가 될 때까지 2초간 sleep 합니다.
# [2차]: 점원이 유니폼 입고 15034번 문 자물쇠를 활짝 열 때까지 2초 동안 기다려줍니다.
time.sleep(2)

# ------------------------------------------------------------------------------
# 3. monitor.sh (순찰 닥터) 출동시켜서 점원 상태 검진하기
# ------------------------------------------------------------------------------

# [1차]: 윈도우 환경에서 리눅스 쉘 스크립트(.sh)를 실행하기 위해 Git Bash의 실행 파일 절대 경로를 지정합니다.
# [2차]: 윈도우 세상에서 리눅스 말(Bash)을 알아듣는 통역관(Git Bash)의 집 주소를 적어둡니다.
bash_path = r"C:\Program Files\Git\bin\bash.exe"

# [1차]: 순찰 닥터(monitor.sh)를 Git Bash로 실행한다는 알림을 출력합니다.
# [2차]: "순찰 닥터(monitor.sh) 출동합니다!"라고 사용자에게 알립니다.
print("[*] Running monitor.sh via Git Bash...")

# [1차]: subprocess.run으로 monitor.sh를 실행하고 끝날 때까지 대기하며 콘솔 출력을 메모리에 캡처(capture_output=True)합니다.
# [2차]: 닥터에게 진료를 시키고, 닥터가 입으로 말한 내용과 적어낸 진료 차트를 전부 받아옵니다.
result = subprocess.run([bash_path, "bin/monitor.sh"], capture_output=True, env=env)

# [1차]: monitor.sh가 터미널에 정상 출력(STDOUT)한 내용을 화면에 구분선과 함께 출력합니다.
# [2차]: 닥터가 "모든 것이 건강합니다!"라고 낭독한 정상 진료 소견서를 모니터에 보여줍니다.
print("\n=== STDOUT (닥터의 정상 보고) ===")
print(result.stdout.decode("utf-8", errors="replace"))

# [1차]: monitor.sh가 경고나 에러(STDERR)로 뿜어낸 내용을 화면에 출력합니다.
# [2차]: 닥터가 "이 환자 체온이 좀 높아요!"라고 지적한 경고 소견서를 모니터에 보여줍니다.
print("=== STDERR (닥터의 에러/경고 보고) ===")
print(result.stderr.decode("utf-8", errors="replace"))

# [1차]: 프로세스 종료 상태 코드(returncode)를 출력합니다. (0: 정상 무사고, 1: 헬스체크 실패)
# [2차]: 닥터가 내린 최종 판정 번호를 보여줍니다. (0점이면 건강 합격, 1점이면 즉시 응급실 직행)
print(f"Exit Code (0이면 성공, 1이면 장애): {result.returncode}")

# ------------------------------------------------------------------------------
# 4. 실습 완료 후 점원 퇴근시키기 (정리 작업)
# ------------------------------------------------------------------------------

# [1차]: 실습이 끝났으므로 점원 앱 프로세스를 안전하게 종료한다는 안내를 출력합니다.
# [2차]: "오늘 시연 끝났으니 점원 퇴근시킵니다"라고 알려줍니다.
print("\n[*] Shutting down agent_app.py...")

# [1차]: app_proc 프로세스에 SIGTERM(종료 신호)을 보내서 안전한 종료(graceful shutdown)를 요청합니다.
# [2차]: 점원 어깨를 톡톡 치며 "오늘 영업 끝났으니 문 닫고 퇴근하세요"라고 점잖게 신호를 줍니다.
app_proc.terminate()

# [1차]: 점원 프로세스가 소켓을 닫고 종료할 때까지 최대 2초 동안 기다립니다.
# [2차]: 점원이 짐 싸서 가게 문 잠그고 나갈 때까지 2초 기다려줍니다.
try:
    app_proc.wait(timeout=2)
except Exception:
    # [1차]: 2초가 지나도 종료되지 않으면 SIGKILL(강제 종료)로 프로세스를 즉시 사살합니다.
    # [2차]: 2초가 지나도 퇴근 안 하고 버티면 전원 차단기를 강제로 내려버립니다.
    app_proc.kill()

# [1차]: 로컬 데모가 성공적으로 완료되었음을 알리고 생성된 로그 경로를 안내합니다.
# [2차]: "모든 실습 완료! 작성된 일기장은 logs/monitor.log에서 확인하세요"라고 인사합니다.
print("[*] Demo finished! Check logs in './logs/monitor.log'")
