#!/bin/bash
# ==============================================================================
# Script Name : verify_all.sh
# Description : 8대 필수 증거자료 수집 및 검증 자동화 스크립트
#               (과제 제출용 실측 로그 및 화면 캡처용 원스톱 도구)
# Target OS   : Ubuntu 22.04 LTS
# Usage       : ./scripts/verify_all.sh
# ==============================================================================

# [1차]: AGENT_HOME 환경 변수가 비어있으면 기본값(/home/agent-admin/agent-app)을 사용합니다.
# [2차]: 증거를 채취하러 갈 에이전트 본사 사무실 주소를 확정합니다.
AGENT_HOME="${AGENT_HOME:-/home/agent-admin/agent-app}"

# [1차]: AGENT_LOG_DIR 환경 변수가 비어있으면 기본값(/var/log/agent-app)을 사용합니다.
# [2차]: 순찰 일지 서류를 확인할 의무기록실 주소를 확정합니다.
LOG_DIR="${AGENT_LOG_DIR:-/var/log/agent-app}"

# [1차]: 검증 도구 시작을 알리는 안내 배너를 화면에 출력합니다.
# [2차]: 8대 필수 증거 검증 시작 현수막을 펼칩니다.
echo "======================================================================"
echo "    Codyssey B4-1 8대 필수 증거자료 자동 검증 및 출력 도구"
echo "======================================================================"

# [1차]: 터미널 가독성을 위해 빈 줄을 한 칸 출력합니다.
# [2차]: 보고서 줄바꿈 공백을 넣습니다.
echo ""

# ----------------------------------------------------------------------
# [증거 1] SSH 포트(20022) 및 Root 접속 차단(PermitRootLogin no) 검증
# ----------------------------------------------------------------------
# [1차]: 증거 1번 섹션 헤더를 출력합니다.
# [2차]: "첫 번째 증거: SSH 비밀문과 사장님 차단 여부를 확인합니다"라고 알립니다.
echo "----------------------------------------------------------------------"
echo "[증거 1] SSH 포트(20022) 및 Root 접속 차단(PermitRootLogin no) 검증"
echo "----------------------------------------------------------------------"

# [1차]: /etc/ssh/sshd_config.d/codyssey.conf 커스텀 설정 파일이 존재하는지 검사합니다.
# [2차]: 우리가 세워둔 SSH 보안 설정 쪽지가 서류함에 있는지 확인합니다.
if [ -f /etc/ssh/sshd_config.d/codyssey.conf ]; then
    # [1차]: 설정 파일의 전체 내용을 터미널에 그대로 출력(cat)합니다.
    # [2차]: 쪽지에 적힌 규칙(Port 20022, PermitRootLogin no)을 소리 내어 읽습니다.
    cat /etc/ssh/sshd_config.d/codyssey.conf
else
    # [1차]: 커스텀 파일이 없으면 메인 sshd_config에서 Port와 PermitRootLogin 줄만 정규식으로 뽑아냅니다.
    # [2차]: 메인 설계도에서 해당 보안 항목만 돋보기로 찾아 출력합니다.
    grep -E "^(Port|PermitRootLogin)" /etc/ssh/sshd_config || echo "Check /etc/ssh configuration"
fi

# [1차]: 터미널 가독성을 위해 빈 줄을 출력합니다.
# [2차]: 줄바꿈을 넣습니다.
echo ""

# [1차]: SSH 수신 대기(Listening) 포트의 실측 상태를 안내하는 텍스트를 출력합니다.
# [2차]: "실제로 20022번 문 뒤에 수문장이 서 있는지 엿보겠습니다"라고 알립니다.
echo ">> SSH Listening Port 상태:"

# [1차]: ss -tulnp 명령어로 열려있는 모든 소켓을 조회하고 20022번 포트나 sshd 데몬 문자열을 grep으로 필터링합니다.
# [2차]: 건물 문고리 명단을 쫙 펼쳐서 '20022번'에 진짜 경비원(sshd)이 서 있는지 현장 검증합니다.
ss -tulnp 2>/dev/null | grep -E "(:20022\b|sshd)" || echo "(sshd listen 확인 필요)"

# [1차]: 터미널 구분을 위해 빈 줄을 출력합니다.
# [2차]: 줄바꿈을 넣습니다.
echo ""

# ----------------------------------------------------------------------
# [증거 2] 방화벽(UFW) 활성화 및 허용 포트(20022/tcp, 15034/tcp) 검증
# ----------------------------------------------------------------------
# [1차]: 증거 2번 섹션 헤더를 출력합니다.
# [2차]: "두 번째 증거: 외곽 검문소(방화벽) 규칙을 확인합니다"라고 알립니다.
echo "----------------------------------------------------------------------"
echo "[증거 2] 방화벽(UFW) 활성화 및 허용 포트(20022/tcp, 15034/tcp) 검증"
echo "----------------------------------------------------------------------"

# [1차]: ufw 명령어가 시스템에 설치되어 있는지 command -v 로 확인합니다.
# [2차]: 우리 성에 UFW 경비원이 채용되어 있는지 확인합니다.
if command -v ufw >/dev/null 2>&1; then
    # [1차]: ufw status verbose로 활성화 여부(Status: active)와 인바운드 허용 룰(20022, 15034)을 상세 출력합니다.
    # [2차]: 경비원에게 "현재 차단기 올라가 있습니까? 누구누구 통과시키고 있습니까?" 하고 근무 장부를 확인합니다.
    ufw status verbose 2>/dev/null || sudo ufw status verbose
else
    # [1차]: UFW가 없는 환경일 경우 firewall-cmd 등의 상태를 대안으로 조회합니다.
    # [2차]: 다른 종류의 방화벽 경비원이 있는지 확인해 봅니다.
    echo "UFW not found or firewall-cmd state:"
    firewall-cmd --list-all 2>/dev/null || true
fi

# [1차]: 터미널 구분을 위해 빈 줄을 출력합니다.
# [2차]: 줄바꿈을 넣습니다.
echo ""

# ----------------------------------------------------------------------
# [증거 3] 계정 및 그룹 구성(agent-admin/dev/test, agent-common/core) 검증
# ----------------------------------------------------------------------
# [1차]: 증거 3번 섹션 헤더를 출력합니다.
# [2차]: "세 번째 증거: 사원증과 부서 명단을 대조합니다"라고 알립니다.
echo "----------------------------------------------------------------------"
echo "[증거 3] 계정 및 그룹 구성(agent-admin/dev/test, agent-common/core) 검증"
echo "----------------------------------------------------------------------"

# [1차]: 그룹 정보 출력 안내 라벨을 출력합니다.
# [2차]: "부서 목록:" 라벨을 붙입니다.
echo ">> Groups:"

# [1차]: getent group agent-common 으로 공통 그룹의 존재와 소속 멤버 명단을 확인합니다.
# [2차]: '일반 사원증(agent-common)' 부서 명부를 열어봅니다.
getent group agent-common || true

# [1차]: getent group agent-core 로 핵심 보안 그룹의 존재와 소속 멤버 명단을 확인합니다.
# [2차]: '보안 구역 카드(agent-core)' 부서 명부를 열어봅니다.
getent group agent-core || true

# [1차]: 터미널 구분을 위해 빈 줄을 출력합니다.
# [2차]: 줄바꿈을 넣습니다.
echo ""

# [1차]: 사용자 ID 정보 출력 안내 라벨을 출력합니다.
# [2차]: "직원 개인 신상 카드:" 라벨을 붙입니다.
echo ">> Users ID Info:"

# [1차]: id agent-admin 으로 운영팀장의 UID, GID, 보조 그룹(sudo, agent-common, agent-core)을 확인합니다.
# [2차]: 운영팀장(admin)의 사원증을 확인합니다. (사장님 도장 sudo가 찍혀 있어야 함)
id agent-admin 2>/dev/null || echo "agent-admin user not found"

# [1차]: id agent-dev 로 개발자의 UID, GID, 소속 그룹(agent-core, agent-common)을 확인합니다.
# [2차]: 개발자(dev)의 사원증을 확인합니다. (금고 카드는 있지만 sudo는 없어야 함)
id agent-dev 2>/dev/null || echo "agent-dev user not found"

# [1차]: id agent-test 로 테스터의 UID, GID, 소속 그룹(agent-common ONLY)을 확인합니다.
# [2차]: 인턴 테스터(test)의 사원증을 확인합니다. (금고 카드가 없어야 함)
id agent-test 2>/dev/null || echo "agent-test user not found"

# [1차]: 터미널 구분을 위해 빈 줄을 출력합니다.
# [2차]: 줄바꿈을 넣습니다.
echo ""

# ----------------------------------------------------------------------
# [증거 4] 디렉토리 구조 및 권한(ACL 포함) 검증
# ----------------------------------------------------------------------
# [1차]: 증거 4번 섹션 헤더를 출력합니다.
# [2차]: "네 번째 증거: 각 방의 도어락 비밀번호(권한)와 추가 열쇠(ACL)를 확인합니다"라고 알립니다.
echo "----------------------------------------------------------------------"
echo "[증거 4] 디렉토리 구조 및 권한(ACL 포함) 검증"
echo "----------------------------------------------------------------------"

# [1차]: 디렉토리 권한 출력 안내 라벨을 출력합니다.
# [2차]: "문고리 기본 자물쇠(ls -ld):" 라벨을 붙입니다.
echo ">> Directory Permissions (ls -ld):"

# [1차]: upload_files의 권한(2770, drwxrws---)과 소유자(agent-admin:agent-common)를 조회합니다.
# [2차]: 공용 택배 창고 문의 자물쇠를 확인합니다. (공용 사원증으로 열 수 있는지 확인)
ls -ld "${AGENT_HOME}/upload_files" 2>/dev/null || true

# [1차]: api_keys의 권한(750, drwxr-x---)과 소유자(agent-admin:agent-core)를 조회합니다.
# [2차]: 비밀 금고 문의 자물쇠를 확인합니다. (테스터는 못 열게 잠겼는지 확인)
ls -ld "${AGENT_HOME}/api_keys" 2>/dev/null || true

# [1차]: /var/log/agent-app의 권한(775, drwxrwxr-x)과 소유자(agent-admin:agent-core)를 조회합니다.
# [2차]: 순찰 일지 보관실 문의 자물쇠를 확인합니다.
ls -ld "${LOG_DIR}" 2>/dev/null || true

# [1차]: monitor.sh 스크립트의 권한(750, -rwxr-x---)과 소유자(agent-dev:agent-core)를 조회합니다.
# [2차]: 닥터(monitor.sh)의 명찰과 출입증을 확인합니다.
ls -l "${AGENT_HOME}/bin/monitor.sh" 2>/dev/null || true

# [1차]: 터미널 구분을 위해 빈 줄을 출력합니다.
# [2차]: 줄바꿈을 넣습니다.
echo ""

# [1차]: POSIX ACL 상세 점검 안내 라벨을 출력합니다.
# [2차]: "추가 특수 열쇠 목록(getfacl):" 라벨을 붙입니다.
echo ">> ACL Inspection (getfacl):"

# [1차]: getfacl 명령어가 시스템에 설치되어 있는지 확인합니다.
# [2차]: 정밀 열쇠 스캐너(getfacl)가 준비되어 있는지 봅니다.
if command -v getfacl >/dev/null 2>&1; then
    # [1차]: upload_files 폴더에 상속(default) 설정된 group:agent-common:rwx ACL을 출력합니다.
    # [2차]: 창고 방에 새 상자를 넣을 때 공용 라벨이 자동 부착되는 규칙을 스캔합니다.
    getfacl "${AGENT_HOME}/upload_files" 2>/dev/null || true
    echo "---"
    # [1차]: api_keys 폴더의 ACL을 출력하여 타인 권한이 배제되어 있는지 확인합니다.
    # [2차]: 비밀 금고 방에 불필요한 뒷구멍 열쇠가 없는지 스캔합니다.
    getfacl "${AGENT_HOME}/api_keys" 2>/dev/null || true
fi

# [1차]: 터미널 구분을 위해 빈 줄을 출력합니다.
# [2차]: 줄바꿈을 넣습니다.
echo ""

# ----------------------------------------------------------------------
# [증거 5] 앱 프로세스 및 포트 15034 LISTEN 상태 검증
# ----------------------------------------------------------------------
# [1차]: 증거 5번 섹션 헤더를 출력합니다.
# [2차]: "다섯 번째 증거: 점원이 출근해 있고 15034번 문이 열려 있는지 봅니다"라고 알립니다.
echo "----------------------------------------------------------------------"
echo "[증거 5] 앱 프로세스 및 포트 15034 LISTEN 상태 검증"
echo "----------------------------------------------------------------------"

# [1차]: 프로세스 실행 상태 안내 라벨을 출력합니다.
# [2차]: "점원 출근 현황:" 라벨을 붙입니다.
echo ">> Process Status:"

# [1차]: pgrep -fl 로 agent_app.py 프로세스가 메모리에 떠 있는지 프로세스 ID와 이름을 검색 출력합니다.
# [2차]: 매장 카운터에 점원(agent_app.py)이 앉아 일하고 있는지 직접 눈으로 확인합니다.
pgrep -fl "agent_app.py" || echo "agent_app.py is not running."

# [1차]: 터미널 구분을 위해 빈 줄을 출력합니다.
# [2차]: 줄바꿈을 넣습니다.
echo ""

# [1차]: 포트 15034 리슨 상태 안내 라벨을 출력합니다.
# [2차]: "15034번 출입문 열림 상태:" 라벨을 붙입니다.
echo ">> Port 15034 Status:"

# [1차]: ss -tulnp 로 TCP 포트 15034가 열려 손님 접속을 LISTEN 중인지 실측 확인합니다.
# [2차]: 15034번 문손잡이가 활짝 열려 손님을 맞이할 준비가 끝났는지 확인합니다.
ss -tulnp 2>/dev/null | grep -E "(:15034\b)" || echo "Port 15034 is not listening."

# [1차]: 터미널 구분을 위해 빈 줄을 출력합니다.
# [2차]: 줄바꿈을 넣습니다.
echo ""

# ----------------------------------------------------------------------
# [증거 6] monitor.sh 직접 실행 결과 확인
# ----------------------------------------------------------------------
# [1차]: 증거 6번 섹션 헤더를 출력합니다.
# [2차]: "여섯 번째 증거: 닥터(monitor.sh)를 출동시켜 즉석 진단 결과를 확인합니다"라고 알립니다.
echo "----------------------------------------------------------------------"
echo "[증거 6] monitor.sh 직접 실행 결과 확인"
echo "----------------------------------------------------------------------"

# [1차]: AGENT_HOME의 bin 폴더에 monitor.sh가 있는지 확인하고 실행합니다.
# [2차]: 정식 도구실에 닥터가 있으면 닥터에게 즉시 순찰을 돌라고 시킵니다.
if [ -f "${AGENT_HOME}/bin/monitor.sh" ]; then
    bash "${AGENT_HOME}/bin/monitor.sh"
# [1차]: 현재 디렉토리 기준 ./bin/monitor.sh 가 있으면 대안으로 실행합니다.
# [2차]: 만약 개발 중인 로컬 폴더에 닥터가 있으면 그 닥터를 대신 출동시킵니다.
elif [ -f "./bin/monitor.sh" ]; then
    bash "./bin/monitor.sh"
fi

# [1차]: 터미널 구분을 위해 빈 줄을 출력합니다.
# [2차]: 줄바꿈을 넣습니다.
echo ""

# ----------------------------------------------------------------------
# [증거 7] /var/log/agent-app/monitor.log 누적 로그 확인
# ----------------------------------------------------------------------
# [1차]: 증거 7번 섹션 헤더를 출력합니다.
# [2차]: "일곱 번째 증거: 일기장에 최근 진단 기록이 잘 적혔는지 확인합니다"라고 알립니다.
echo "----------------------------------------------------------------------"
echo "[증거 7] /var/log/agent-app/monitor.log 누적 로그 확인"
echo "----------------------------------------------------------------------"

# [1차]: 시스템 정식 로그 경로(${LOG_DIR}/monitor.log)가 존재하면 tail -n 10으로 최근 10줄을 읽어옵니다.
# [2차]: 의무기록실에 쌓인 일기장의 맨 뒤 10줄을 펼쳐서 봅니다.
if [ -f "${LOG_DIR}/monitor.log" ]; then
    tail -n 10 "${LOG_DIR}/monitor.log"
# [1차]: 로컬 실습 경로(./logs/monitor.log)가 존재하면 해당 파일의 최근 10줄을 읽어옵니다.
# [2차]: 로컬 서류함에 저장된 일기장의 맨 뒤 10줄을 펼쳐서 봅니다.
elif [ -f "./logs/monitor.log" ]; then
    tail -n 10 "./logs/monitor.log"
else
    # [1차]: 로그 파일이 없을 경우 안내 문구를 출력합니다.
    # [2차]: 아직 작성된 일기장이 없다고 알려줍니다.
    echo "No log file found at ${LOG_DIR}/monitor.log or ./logs/monitor.log"
fi

# [1차]: 터미널 구분을 위해 빈 줄을 출력합니다.
# [2차]: 줄바꿈을 넣습니다.
echo ""

# ----------------------------------------------------------------------
# [증거 8] crontab 매분 등록 및 스케줄링 확인
# ----------------------------------------------------------------------
# [1차]: 증거 8번 섹션 헤더를 출력합니다.
# [2차]: "여덟 번째 증거: 자명종 시계가 매 1분마다 울리게 맞춰져 있는지 봅니다"라고 알립니다.
echo "----------------------------------------------------------------------"
echo "[증거 8] crontab 매분 등록 및 스케줄링 확인"
echo "----------------------------------------------------------------------"

